#!/usr/bin/env node
/**
 * Perf lab — emit a k6 script from a scenario JSON file (offline; no Agent required).
 *
 *   node scripts/load-scenario-to-k6.mjs scenario.json > load.js
 */
import fs from 'node:fs';

const path = process.argv[2];
if (!path) {
  console.error('Usage: node scripts/load-scenario-to-k6.mjs scenario.json');
  process.exit(2);
}
const scn = JSON.parse(fs.readFileSync(path, 'utf8'));
const url = scn.target_url || scn.url || 'http://localhost/';
const method = (scn.method || 'GET').toUpperCase();
const vus = Number(scn.vus) || 5;
const dur = Number(scn.duration_seconds || scn.duration) || 30;
const runId = scn.load_run_id || 'local';
const body = scn.body || '';
const headers = scn.headers || {};

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

let hdrLines = Object.entries(headers)
  .map(([k, v]) => `    '${esc(k)}': '${esc(v)}',`)
  .join('\n');

const script = `// Generated by OPA load-scenario-to-k6.mjs (Perf lab)
import http from 'k6/http';
import { check, sleep } from 'k6';

export const options = { vus: ${vus}, duration: '${dur}s', tags: { load_run_id: '${esc(runId)}' } };

export default function () {
  const params = { headers: {
    'traceparent': \`00-\${__ENV.OPA_TRACE_ID || '00000000000000000000000000000001'}-\${__ENV.OPA_SPAN_ID || '0000000000000001'}-01\`,
    'X-OPA-Load-Run-Id': '${esc(runId)}',
    'baggage': 'opa.load_run_id=${esc(runId)}',
${hdrLines}
  }};
  const res = ${method === 'GET' || !body
    ? `http.get('${esc(url)}', params)`
    : `http.request('${esc(method)}', '${esc(url)}', '${esc(body)}', params)`};
  check(res, { 'status < 500': (r) => r.status < 500 });
  sleep(0.1);
}
`;
process.stdout.write(script);
